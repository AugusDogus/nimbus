import { randomUUID } from "node:crypto";
import { expect } from "@playwright/test";
import { test } from "./helpers";
import { adminEmail, client } from "./helpers";

test("WebDAV app passwords support file operations and stop working after revocation", async ({ page, context, request }, testInfo) => {
  const folder = `dav-${randomUUID()}`;
  const device = `Laptop ${randomUUID()}`;
  await page.goto("/settings/webdav");
  await page.getByLabel("Device name").fill(device);
  await page.getByRole("button", { name: "Create password", exact: true }).click();
  const token = page.getByLabel("Save this password now. It is shown only once.");
  await expect(token).toBeVisible();
  const headers = { Authorization: `Basic ${Buffer.from(`${adminEmail}:${await token.inputValue()}`).toString("base64")}` };
  await page.getByRole("button", { name: "I’ve saved it" }).click();
  expect((await request.get("/dav/alpha.txt")).status()).toBe(401);
  expect((await request.fetch(`/dav/${folder}`, { method: "MKCOL", headers })).status()).toBe(201);
  const original = `/dav/${folder}/note.txt`;
  expect((await request.put(original, { headers, data: "Created through WebDAV" })).status()).toBe(201);
  const get = await request.get(original, { headers });
  expect(get.status()).toBe(200);
  expect(await get.text()).toBe("Created through WebDAV");
  expect((await request.put(original, { headers: { ...headers, "If-Match": '"stale-version"' }, data: "Stale edit" })).status()).toBe(412);
  const range = await request.get(original, { headers: { ...headers, Range: "bytes=0-6" } });
  expect(range.status()).toBe(206);
  expect(await range.text()).toBe("Created");
  const propfind = await request.fetch(`/dav/${folder}/`, { method: "PROPFIND", headers: { ...headers, Depth: "1" } });
  expect(propfind.status()).toBe(207);
  expect(await propfind.text()).toContain("note.txt");
  const renamed = `/dav/${folder}/renamed.txt`;
  expect((await request.fetch(original, { method: "MOVE", headers: { ...headers, Destination: `http://localhost:3100${renamed}` } })).status()).toBe(201);
  expect((await request.get(original, { headers })).status()).toBe(404);
  expect((await request.get(renamed, { headers })).status()).toBe(200);
  const lock = await request.fetch(renamed, { method: "LOCK", headers });
  expect(lock.status()).toBe(200);
  expect((await request.put(renamed, { headers, data: "Must not overwrite a locked file" })).status()).toBe(423);
  const lockToken = lock.headers()["lock-token"];
  if (!lockToken) throw new Error("WebDAV LOCK did not return a lock token.");
  const rpc = await client(context);
  await expect(rpc.files.rename.mutate({ path: `${folder}/renamed.txt`, newName: "locked-rename.txt" })).rejects.toMatchObject({ data: { code: "CONFLICT" } });
  await expect(rpc.files.delete.mutate({ path: `${folder}/renamed.txt` })).rejects.toMatchObject({ data: { code: "CONFLICT" } });
  expect((await request.put(renamed, { headers: { ...headers, If: `(${lockToken})` }, data: "Saved with the lock token" })).status()).toBe(204);
  expect((await request.fetch(renamed, { method: "UNLOCK", headers: { ...headers, "Lock-Token": lockToken } })).status()).toBe(204);
  expect((await request.delete(renamed, { headers })).status()).toBe(204);
  expect((await request.get(renamed, { headers })).status()).toBe(404);
  const deviceRow = page.locator("div.border-t").filter({ hasText: device });
  await deviceRow.getByRole("button", { name: "Revoke", exact: true }).click();
  await page.getByRole("alertdialog", { name: "Revoke app password?" }).getByRole("button", { name: "Revoke", exact: true }).click();
  await expect(deviceRow).toHaveCount(0);
  expect((await request.get("/dav/alpha.txt", { headers })).status()).toBe(401);
  await page.evaluate(async () => {
    window.scrollTo(0, 0);
    document.querySelectorAll('[role="dialog"]').forEach((dialog) => dialog.scrollTo(0, 0));
    await new Promise(requestAnimationFrame);
    await new Promise(requestAnimationFrame);
  });
  await page.screenshot({ path: testInfo.outputPath("settings.png"), fullPage: true });
});
