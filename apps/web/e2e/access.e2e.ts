import { randomUUID } from "node:crypto";
import { expect } from "@playwright/test";
import { test } from "./helpers";
import { action, client, createFolder, login, password, upload } from "./helpers";

test("administrators create groups and members receive only their granted read or write access", async ({ page, context, browser, isMobile }, testInfo) => {
  const suffix = randomUUID();
  const email = `member-${suffix}@nimbus.test`;
  const name = `Member ${suffix}`;
  const group = `Editors ${suffix}`;
  const folder = `team-${suffix}`;
  const rpc = await client(context);
  await page.goto("/admin");
  await page.getByLabel("Name", { exact: true }).fill(name);
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Initial password").fill(password);
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByLabel(`${name} (${email})`, { exact: true })).toBeVisible();
  await page.getByLabel("Group name").fill(group);
  await page.getByLabel(`${name} (${email})`, { exact: true }).check();
  await page.getByRole("button", { name: "Create group", exact: true }).click();
  await expect(page.getByText(`${group} · 1 members`, { exact: true })).toBeVisible();
  await page.evaluate(async () => {
    window.scrollTo(0, 0);
    document.querySelectorAll('[role="dialog"]').forEach((dialog) => dialog.scrollTo(0, 0));
    await new Promise(requestAnimationFrame);
    await new Promise(requestAnimationFrame);
  });
  await page.screenshot({ path: testInfo.outputPath("administration.png"), fullPage: true });
  await page.goto("/");
  await createFolder(page, folder, isMobile);
  await page.getByRole("link", { name: folder, exact: true }).click();
  await expect(page).toHaveURL(`/browse/${folder}`);
  await expect(page.getByRole("heading", { name: "This folder is empty" })).toBeVisible();
  await upload(page, "team-note.txt", "Members can read this file.");
  await page.goto("/");
  await action(page, folder, "Share", isMobile);
  const sharing = page.getByRole("dialog", { name: `Share ${folder}`, exact: true });
  await sharing.getByRole("combobox", { name: "Person or group", exact: true }).click();
  await page.getByRole("option", { name: `Group: ${group}`, exact: true }).click();
  await sharing.getByRole("button", { name: "Grant access", exact: true }).click();
  await expect(sharing.getByText(`${group} · read`, { exact: true })).toBeVisible();
  const memberContext = await browser.newContext({ storageState: { cookies: [], origins: [] }, viewport: page.viewportSize() });
  try {
    const closedSignup = await memberContext.request.post("/api/auth/sign-up/email", { data: { name: "Uninvited", email: `uninvited-${suffix}@nimbus.test`, password } });
    expect(closedSignup.status()).toBe(403);
    const member = await memberContext.newPage();
    await login(member, email);
    const memberRPC = await client(memberContext);
    expect((await memberRPC.access.me.query()).isAdmin).toBe(false);
    expect((await memberRPC.files.list.query({})).map((entry) => entry.name)).toEqual([folder]);
    expect((await memberContext.request.get("/api/files/download?path=alpha.txt")).status()).toBe(403);
    const allowed = await memberContext.request.get(`/api/files/download?path=${encodeURIComponent(`${folder}/team-note.txt`)}`);
    expect(allowed.status()).toBe(200);
    expect(await allowed.text()).toBe("Members can read this file.");
    await expect(memberRPC.files.createFolder.mutate({ path: folder, name: "forbidden" })).rejects.toMatchObject({ data: { code: "FORBIDDEN" } });
    await expect(memberRPC.access.saveGroup.mutate({ name: "Unauthorized", memberIds: [] })).rejects.toMatchObject({ data: { code: "FORBIDDEN" } });
    await member.goto("/shared");
    await expect(member.getByRole("link", { name: folder, exact: true })).toBeVisible();
    await member.getByRole("link", { name: folder, exact: true }).click();
    await expect(member).toHaveURL(`/browse/${folder}`);
    await expect(member.getByRole("button", { name: "Actions for team-note.txt" })).toBeVisible();
    await member.getByRole("button", { name: "Actions for team-note.txt" }).click();
    await expect(member.getByRole(isMobile ? "button" : "menuitem", { name: "Rename", exact: true })).toHaveCount(0);
    await member.reload();
    await sharing.getByRole("combobox", { name: "Permission", exact: true }).click();
    await page.getByRole("option", { name: "Edit files", exact: true }).click();
    await sharing.getByRole("button", { name: "Grant access", exact: true }).click();
    await expect(sharing.getByText(`${group} · write`, { exact: true })).toBeVisible();
    await member.reload();
    await createFolder(member, "member-created", isMobile);
    expect((await rpc.files.list.query({ path: folder })).map((entry) => entry.name)).toContain("member-created");
    await member.getByRole("button", { name: "Actions for member-created", exact: true }).click();
    await expect(member.getByRole(isMobile ? "button" : "menuitem", { name: "Rename", exact: true })).toHaveCount(0);
    await expect(member.getByRole(isMobile ? "button" : "menuitem", { name: "Move", exact: true })).toHaveCount(0);
    await sharing.getByRole("button", { name: "Remove access", exact: true }).click();
    await expect(sharing.getByText("No direct grants. Parent folder permissions still apply.")).toBeVisible();
    expect((await memberContext.request.get(`/api/files/download?path=${encodeURIComponent(`${folder}/team-note.txt`)}`)).status()).toBe(403);
    await member.goto("/admin");
    await expect(member.getByRole("alert").filter({ hasText: "Only server administrators" })).toBeVisible();
  } finally { await memberContext.close(); }
  await page.goto("/admin");
  const groupRow = page.locator("div.border-t").filter({ hasText: `${group} · 1 members` });
  await groupRow.getByRole("button", { name: "Edit", exact: true }).click();
  await expect(page.getByRole("button", { name: "Save group", exact: true })).toBeVisible();
  await groupRow.getByRole("button", { name: "Delete", exact: true }).click();
  await page.getByRole("alertdialog", { name: "Delete group and revoke its access?" }).getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(page.getByLabel("Group name")).toHaveValue("");
  await expect(page.getByRole("button", { name: "Create group", exact: true })).toBeVisible();
});
